"""Generate app/src/gui/colormaps.cpp: 256-entry magma, inferno and viridis tables (RESTYLE Phase 2).

Usage, from the repository root:
    python tools/python/make_colormaps.py <matplotlib/_cm_listed.py>

Reads the colour lists from matplotlib's _cm_listed.py (for example
https://raw.githubusercontent.com/matplotlib/matplotlib/v3.9.2/lib/matplotlib/_cm_listed.py) by
parsing it, never importing or running it. The colormaps are by Nathaniel J. Smith, Stefan van der
Walt and Eric Firing, released under CC0 (https://github.com/BIDS/colormap), so the tables can be
compiled into the app.
"""

import ast
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "app" / "src" / "gui" / "colormaps.cpp"
NAMES = {"magma": "_magma_data", "inferno": "_inferno_data", "viridis": "_viridis_data"}


def main() -> int:
    tree = ast.parse(pathlib.Path(sys.argv[1]).read_text(encoding="utf-8"))
    data = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1:
            target = node.targets[0]
            if isinstance(target, ast.Name) and target.id in NAMES.values():
                data[target.id] = ast.literal_eval(node.value)
    lines = [
        "// Generated by tools/python/make_colormaps.py from matplotlib's colour lists. Do not edit.",
        "// Magma, inferno and viridis by Nathaniel J. Smith, Stefan van der Walt and Eric Firing,",
        "// CC0 (https://github.com/BIDS/colormap).",
        "",
        '#include "gui/colormaps.h"',
        "",
        "namespace psyight {",
        "",
        "namespace {",
        "",
    ]
    for name, var in NAMES.items():
        rows = data[var]
        assert len(rows) == 256, (name, len(rows))
        lines.append(f"constexpr ColourTable k{name.capitalize()} = {{")
        packed = []
        for r, g, b in rows:
            ri, gi, bi = (max(0, min(255, round(v * 255))) for v in (r, g, b))
            packed.append(f"0xFF{bi:02X}{gi:02X}{ri:02X}u")  # IM_COL32 order: ABGR.
        for i in range(0, 256, 6):
            lines.append("    " + ", ".join(packed[i:i + 6]) + ",")
        lines.append("};")
        lines.append("")
    lines += [
        "} // namespace",
        "",
        "const ColourTable &colormap_table(Colormap map) {",
        "    switch (map) {",
        "    case Colormap::magma:",
        "        return kMagma;",
        "    case Colormap::inferno:",
        "        return kInferno;",
        "    case Colormap::viridis:",
        "        return kViridis;",
        "    }",
        "    return kMagma;",
        "}",
        "",
        "} // namespace psyight",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
